#!/usr/bin/env node
// Bundle the AudioWorklet processor (engine included) into one ES module, written twice:
//   dist/worklet.js                    a file hosts can serve and pass as `workletUrl`
//   src/worklet/code.generated.ts      the same code as a string, which createSynth loads from a Blob URL
// Both are git-ignored. `test`, `typecheck` and `build` run this first; the editor's dev/build run it too.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [path.join(root, "src/worklet/processor.ts")],
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  write: false,
});
const code = result.outputFiles[0]!.text;

mkdirSync(path.join(root, "dist"), { recursive: true });
writeFileSync(path.join(root, "dist/worklet.js"), code);
writeFileSync(
  path.join(root, "src/worklet/code.generated.ts"),
  `// Generated by scripts/build-worklet.ts from src/worklet/processor.ts. Don't edit.\nexport default ${JSON.stringify(code)};\n`,
);
console.log(`worklet: ${(code.length / 1024).toFixed(1)} kB -> dist/worklet.js, src/worklet/code.generated.ts`);
